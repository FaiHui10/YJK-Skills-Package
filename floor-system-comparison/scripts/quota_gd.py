# 钢筋子目：定额消耗量(t/t) 与 定额内钢筋单价(元/t, 2018水平)
REBAR_DOSE = {"A1-5-105": 1.020, "A1-5-106": 1.025, "A1-5-107": 1.025}
REBAR_QUOTA_PRICE = {"A1-5-105": 3738.53, "A1-5-106": 3547.15, "A1-5-107": 3547.15}

# 混凝土子目：预拌混凝土消耗量 (10.100)/(10m³) = 1.010 m³/m³，定额内为未计价主材
CONC_LOSS = 1.010

# ------------------------------------------------------------ 取费标准
PROFIT = 0.20        # 工程利润 = (定额人工+定额机具) × 20%
VAT = 0.09           # 增值税 9%

# ------------------------------------------------------- 广州 2026-06 信息价
# 穗建造价〔2026〕62 号（税前综合价格，元/m³ 泵送预拌混凝土）
CONC_PRICE_PUMP = {"C30": 382.5, "C35": 399.0, "C40": 416.5, "C45": 433.5,
                   "C50": 451.5, "C55": 469.5, "C60": 485.5}
CONC_PRICE = {"C25": 364.0, "C30": 375.5, "C35": 391.5, "C40": 408.5,
              "C45": 426.5, "C50": 444.5, "C55": 461.5, "C60": 479.0}
# 螺纹钢筋 HRB400E（元/t）
REBAR_PRICE = {"Φ10内": 3168.0, "Φ10外": 3143.0, "Φ12-25": 3089.0, "Φ25外": 3147.0}
LABOR_INDEX = 1.0913      # 穗建造价〔2026〕62 号 人工费价格指数（含机上人工）

# 直径 → (定额子目, 信息价类别)
DIA_MAP = [
    (10, "A1-5-105", "Φ10内"),
    (25, "A1-5-106", "Φ12-25"),
    (999, "A1-5-107", "Φ25外"),
]


def rebar_class(dia_mm):
    """按钢筋直径(mm)返回 (定额子目编号, 信息价类别)。"""
    for lim, code, spec in DIA_MAP:
        if dia_mm <= lim:
            return code, spec
    return DIA_MAP[-1][1], DIA_MAP[-1][2]


class Pricer(object):
    """按广州口径计算综合单价 (除税, 含税)。labor_index 默认 1.0（定额人工原值）。"""

    def __init__(self, labor_index=1.0, conc_pump=True, height_m=4.8):
        self.ki = labor_index
        self.conc = CONC_PRICE_PUMP if conc_pump else CONC_PRICE
        self.height = height_m

    # ---------------- 通用：基价 -> (除税, 含税) ----------------
    def _base(self, code, div):
        """定额基价(含管理费) 折算到计价单位，并叠加利润。返回 (施工费, 除数, 各项)。"""
        name, u, base, lab, mat, mac, mgr = QUOTA[code]
        lab, mac, mgr = lab * self.ki, mac * self.ki, mgr * self.ki
        work = (lab + mat + mac + mgr + (lab + mac) * PROFIT) / div
        return work, lab / div, mat / div, mac / div, mgr / div

    # ---------------- 混凝土（梁 / 板）----------------
    def conc_unit(self, code, grade):
        """元/m³：(除税, 含税, 明细dict)。主材=泵送预拌混凝土信息价×1.010。"""
        work, lab, mat, mac, mgr = self._base(code, 10.0)
        c = self.conc[grade]
        cm = c * CONC_LOSS
        net = work + cm
        return net, net * (1 + VAT), {
            "定额": code, "名称": QUOTA[code][0],
            "定额基价/10": QUOTA[code][2] / 10.0,
            "利润": (lab + mac) * PROFIT,
            "混凝土": cm, "混凝土级别": grade, "混凝土信息价": c,
        }

    # ---------------- 钢筋 ----------------
    def rebar_unit(self, dia_mm):
        """元/t：(除税, 含税, 明细dict)。"""
        code, spec = rebar_class(dia_mm)
        name, u, base, lab, mat, mac, mgr = QUOTA[code]
        other = mat - REBAR_DOSE[code] * REBAR_QUOTA_PRICE[code]   # 其他材料费
        lab, mac, mgr = lab * self.ki, mac * self.ki, mgr * self.ki
        work = lab + other + mac + mgr
        prof = (lab + mac) * PROFIT
        m = REBAR_DOSE[code] * REBAR_PRICE[spec]
        net = work + prof + m
        return net, net * (1 + VAT), {
            "定额": code, "名称": name, "信息价类别": spec,
            "施工费": work, "利润": prof, "钢筋材料": m,
            "钢筋单价": REBAR_PRICE[spec],
        }

    # ---------------- 模板 ----------------
    def _n_add(self, h=None):
        h = self.height if h is None else h
        if h <= 3.6:
            return 0
        n = -(-(h - 3.6) // 1)          # 向上取整（不足1m按1m计）
        return int(n)

    def form_unit(self, kind, b_mm=None, h=None):
        """元/m²：(除税, 含税, 明细dict)。
        kind='beam' 时按梁宽选 A1-20-33/34；kind='slab' 用 A1-20-75。
        """
        n = self._n_add(h)
        if kind == "beam":
            code = "A1-20-33" if (b_mm or 0) <= 250 else "A1-20-34"
            add = "A1-20-40"
        else:
            code, add = "A1-20-75", "A1-20-79"
        work, lab, mat, mac, mgr = self._base(code, 100.0)
        tot = work
        detail = {code: 1, "名称": QUOTA[code][0], "基价": QUOTA[code][2] / 100.0,
                  "利润": (lab + mac) * PROFIT, "超高次数": n}
        if n:
            aw, al, am, ac, ag = self._base(add, 100.0)
            tot += aw * n
            detail[add] = n
            detail["超高名称"] = QUOTA[add][0]
            detail["超高基价"] = QUOTA[add][2] / 100.0
            detail["超高利润"] = (al + ac) * PROFIT * n
        return tot, tot * (1 + VAT), detail
