# ---------------------------------------------------------- 广州市信息价
# 穗建造价〔2026〕62 号《2026年6月广州地区建设工程常用材料税前综合价格》
CONC_PRICE = {"C25": 364.0, "C30": 375.5, "C35": 391.5, "C40": 408.5, "C45": 426.5,
              "C50": 444.5, "C55": 461.5, "C60": 479.0}          # 非泵送
CONC_PRICE_PUMP = {"C30": 382.5, "C35": 399.0, "C40": 416.5, "C45": 433.5,
                   "C50": 451.5, "C55": 469.5, "C60": 485.5}     # 泵送
REBAR_PRICE = {"Φ10内": 3168.0, "Φ10外": 3143.0, "Φ12-25": 3089.0, "Φ25外": 3147.0}
PLATE_PRICE_Q355 = [(4.5, 7, 3500.82), (8, 10, 3462.97), (11, 15, 3483.45),
                    (16, 20, 3461.78), (21, 40, 3473.42)]
LABOR_INDEX = 1.0913       # 穗建造价〔2026〕62 号 人工费价格指数（含机上人工）

CONC_LOSS = 1.010          # 混凝土损耗率 1.0%


PLATE_F = 1.0               # 钢板价格调整系数（敏感性分析用）


def plate_price(t_mm):
    """Q355 热轧厚钢板 税前综合价格（元/t）。"""
    for lo, hi, p in PLATE_PRICE_Q355:
        if lo <= t_mm <= hi:
            return p * PLATE_F
    return PLATE_PRICE_Q355[-1][2] * PLATE_F


class Pricer(object):
    """按广州口径计算综合单价（除税 / 含税）。"""

    def __init__(self, labor_index=1.0, conc_pump=True):
        self.ki = labor_index
        self.conc = CONC_PRICE_PUMP if conc_pump else CONC_PRICE

    # ---------- 通用：基价 -> 综合单价（不含未计价主材）----------
    def unit(self, code, div=1.0, sub_main=0.0):
        """返回 (除税综合单价, 含税综合单价)。
        div=单位换算分母（如 10m³ -> 10）；sub_main=需从材料费中扣除的定额主材价（元/定额单位）。
        """
        name, u, base, lab, mat, mac, mgr = QUOTA[code]
        lab, mac = lab * self.ki, mac * self.ki
        mgr = mgr * self.ki          # 管理费以(人工+机具)为基数，同步调整
        net = (lab + mat - sub_main + mac + mgr + (lab + mac) * PROFIT) / div
        return net, net * (1 + VAT)

    # ---------- 混凝土（现浇柱 / 管内混凝土）----------
    def conc_unit(self, grade):
        """元/m³：A1-5-5 施工综合(除税, 不含混凝土材料) + 混凝土材料(信息价×损耗)。"""
        name, u, base, lab, mat, mac, mgr = QUOTA["A1-5-5"]
        lab, mac, mgr = lab * self.ki, mac * self.ki, mgr * self.ki
        work = (lab + mat + mac + mgr + (lab + mac) * PROFIT) / 10.0     # 元/m³ 施工
        c = self.conc[grade] * CONC_LOSS                                # 元/m³ 混凝土材料
        return work + c, (work + c) * (1 + VAT), work, c

    # ---------- 钢筋 ----------
    def rebar_unit(self, code, spec):
        """元/t：施工综合(除税) + 钢筋材料（信息价×损耗）。spec 取 REBAR_PRICE 的键。"""
        name, u, base, lab, mat, mac, mgr = QUOTA[code]
        other = mat - REBAR_DOSE[code] * REBAR_QUOTA_PRICE[code]        # 其他材料费
        lab, mac, mgr = lab * self.ki, mac * self.ki, mgr * self.ki
        work = lab + other + mac + mgr + (lab + mac) * PROFIT
        m = REBAR_DOSE[code] * REBAR_PRICE[spec]
        return work + m, (work + m) * (1 + VAT), work, m

    # ---------- 柱模板（含支模超高）----------
    def form_unit(self, perim_m, h_m, area_m2=None):
        """元/m²：按周长选子目 + 支模高度超过3.6m 每增1m子目。返回 (除税, 含税, 明细)。"""
        if perim_m <= 1.2:
            codes = ["A1-20-14"]
        elif perim_m <= 1.8:
            codes = ["A1-20-15"]
        else:
            codes = ["A1-20-16"]
        detail = {}
        n_add = max(0, int(-(-(h_m - 3.6) // 1))) if h_m > 3.6 else 0
        if n_add:
            codes += ["A1-20-19"] * n_add
        tot = 0.0
        for c in codes:
            name, u, base, lab, mat, mac, mgr = QUOTA[c]
            lab, mac, mgr = lab * self.ki, mac * self.ki, mgr * self.ki
            v = (lab + mat + mac + mgr + (lab + mac) * PROFIT) / 100.0   # 元/m²
            tot += v
            detail[c] = detail.get(c, 0) + 1
        return tot, tot * (1 + VAT), detail

    # ---------- 钢柱安装 ----------
    def steel_erect_unit(self, piece_kg):
        t = piece_kg / 1000.0
        code = "A1-7-30" if t <= 3 else ("A1-7-31" if t <= 5 else
                                        ("A1-7-32" if t <= 10 else "A1-7-33"))
        name, u, base, lab, mat, mac, mgr = QUOTA[code]
        lab, mac, mgr = lab * self.ki, mac * self.ki, mgr * self.ki
        v = lab + mat + mac + mgr + (lab + mac) * PROFIT
        return code, v, v * (1 + VAT)

    # ---------- 金属面防火涂料 ----------
    def fire_unit(self, code):
        name, u, base, lab, mat, mac, mgr = QUOTA[code]
        lab, mac, mgr = lab * self.ki, mac * self.ki, mgr * self.ki
        v = (lab + mat + mac + mgr + (lab + mac) * PROFIT) / 100.0       # 元/m²
        return v, v * (1 + VAT)

    # ---------- 成品钢管柱（钢板 + 制作加工费）----------
    def tube_unit(self, t_mm, fab_cost, loss=0.05):
        """元/t 成品钢管柱（出厂价，含制作、焊接、除锈、车间底漆）。
        构成 = 钢板信息价 × (1+下料损耗) + 制作加工费（市场行情）。
        """
        m = plate_price(t_mm) * (1 + loss) + fab_cost
        return m, m * (1 + VAT)
